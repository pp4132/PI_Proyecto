                <section id="origenes">
                    <h2>Orígenes</h2>
                    <p>
                        El beisbol comenzó a difundirse en México durante la segunda mitad del siglo XIX. Su llegada se relaciona con comerciantes, marineros, trabajadores ferroviarios y viajeros que mantenían contacto con Estados Unidos. No existe un acuerdo absoluto sobre el primer partido celebrado en territorio mexicano, pues distintas regiones, entre ellas Veracruz, Nuevo León y la península de Yucatán, conservan relatos tempranos. Lo importante es que el deporte se extendió gradualmente desde los puertos y ciudades fronterizas hacia otras comunidades, donde aparecieron equipos aficionados y encuentros que reunían a familias y trabajadores.
                    </p>
                </section>

                <section id="primeras_ligas">
                    <h2>Primeras ligas</h2>
                    <p>
                        A finales del siglo XIX y principios del XX, los partidos se volvieron una forma habitual de convivencia. El desarrollo del ferrocarril facilitó los viajes de los clubes y la organización de encuentros entre ciudades. Con el tiempo surgieron parques de pelota, ligas regionales y una afición que identificaba a sus equipos con el orgullo local. El beisbol creció especialmente en el norte y el sureste, aunque también encontró seguidores en la capital y otras zonas del país. Esta expansión preparó el terreno para una competencia profesional estable.
                    </p>
                </section>

                <section id="liga_mexicana">
                    <h2>Liga Mexicana</h2>
                    <p>
                        Un acontecimiento decisivo ocurrió en 1925, cuando se fundó la Liga Mexicana de Beisbol (LMB), cuya primera temporada comenzó el 28 de junio. Entre los impulsores de aquel proyecto destacó Alejandro Aguilar Reyes, conocido como Fray Nano, periodista y promotor del deporte. La nueva liga permitió organizar calendarios, reunir clubes y ofrecer a los jugadores un escenario competitivo de mayor alcance. Durante las décadas siguientes atravesó cambios de equipos, sedes y formatos, pero se convirtió en uno de los pilares del beisbol profesional mexicano.
                    </p>
                </section>

                <section id="expansion">
                    <h2>Expansión del béisbol</h2>
                    <p>
                        En las décadas de 1940 y 1950, el beisbol mexicano atrajo a figuras nacionales y extranjeras y vivió una etapa de gran interés popular. La convivencia de distintas generaciones de peloteros fortaleció el nivel de juego. Posteriormente se consolidaron clubes con aficiones muy fieles y rivalidades históricas. A la vez, la Liga Mexicana del Pacífico desarrolló su propio calendario invernal, distinto del circuito veraniego de la LMB, ampliando las oportunidades para jugadores y aficionados. Las dos competencias han contribuido a mantener vivo el deporte en diferentes regiones.
                    </p>
                </section>

                <section id="zona_norte">
                    <h2>El béisbol en la Zona Norte</h2>
                    <p>
                        El beisbol también ha sido una vía para que peloteros mexicanos destaquen internacionalmente. Fernando Valenzuela, nacido en Sonora, alcanzó fama mundial con los Dodgers de Los Ángeles en 1981 y se convirtió en símbolo de inspiración para nuevas generaciones. Otros jugadores mexicanos han sobresalido en las Grandes Ligas y en torneos internacionales. La selección nacional logró una actuación histórica al llegar a las semifinales del Clásico Mundial de Beisbol de 2023, resultado que atrajo todavía más atención hacia el talento mexicano.
                    </p>
                </section>

                <section id="actualidad">
                    <h2>El béisbol actual</h2>
                    <p>
                        En la actualidad, el beisbol es parte de la identidad cultural de muchas ciudades. Los estadios son espacios de reunión y las camisetas representan tradiciones locales, oficios, paisajes y memorias familiares. Para la temporada 2026, la LMB está organizada en Zona Norte y Zona Sur, con diez equipos en cada una. La Zona Norte reúne clubes históricos y proyectos recientes: Acereros, Algodoneros, Caliente, Charros, Dorados, Rieleros, Saraperos, Sultanes, Tecos y Toros. Sus trayectorias muestran cómo el beisbol mexicano combina continuidad, renovación y pasión regional.
                    </p>
